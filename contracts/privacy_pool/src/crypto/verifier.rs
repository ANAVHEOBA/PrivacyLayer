//! Wrapper around the Noir verifier for the withdraw circuit.

use soroban_sdk::{BytesN, Env, Vec};

/// Simple verifier interface used by the withdraw core logic.
pub struct Verifier<'a> {
    env: &'a Env,
}

impl<'a> Verifier<'a> {
    pub fn new(env: &'a Env) -> Self {
        Self { env }
    }

    /// Verify a proof against the supplied public inputs.
    ///
    /// The verifier expects the public inputs to be provided as a `Vec<u128>`
    /// where each element corresponds to a field element in the circuit.
    pub fn verify(&self, proof: &BytesN<64>, public_inputs: &Vec<u128>) -> bool {
        // The actual verification logic is generated by Noir and compiled into
        // the contract.  Here we forward the call to the generated verifier
        // contract method `verify_proof`.
        //
        // NOTE: The generated verifier expects the public inputs in the exact
        // order defined by the circuit.  No transformation is performed here.
        self.env
            .invoke_contract(
                &self.env.current_contract_address(),
                &symbol!("verify_proof"),
                (proof.clone(), public_inputs.clone()),
            )
            .unwrap_or(false)
    }
}
